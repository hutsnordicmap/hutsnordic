import {
  Anchor,
  Baby,
  Bath,
  BedDouble,
  Bike,
  BookOpen,
  Car,
  Check,
  ChefHat,
  Coffee,
  Disc,
  Fence,
  Flame,
  Footprints,
  House,
  Landmark,
  Mountain,
  Sailboat,
  Shirt,
  Snowflake,
  Tent,
  Users,
  UtensilsCrossed,
  Volleyball,
  Waves,
  Wifi,
  Wind,
  type LucideIcon,
} from "lucide-react";

const icons: Record<string, LucideIcon> = {
  anchor: Anchor,
  baby: Baby,
  bath: Bath,
  bed: BedDouble,
  bike: Bike,
  book: BookOpen,
  car: Car,
  check: Check,
  chef: ChefHat,
  coffee: Coffee,
  disc: Disc,
  fence: Fence,
  flame: Flame,
  footprints: Footprints,
  home: House,
  landmark: Landmark,
  mountain: Mountain,
  sailboat: Sailboat,
  shirt: Shirt,
  snowflake: Snowflake,
  tent: Tent,
  users: Users,
  utensils: UtensilsCrossed,
  volleyball: Volleyball,
  waves: Waves,
  wifi: Wifi,
  wind: Wind,
};

export function Icon({ name, className = "size-5" }: { name: string; className?: string }) {
  const C = icons[name] ?? Check;
  return <C className={className} strokeWidth={1.6} aria-hidden />;
}
